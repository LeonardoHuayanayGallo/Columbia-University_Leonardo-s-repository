class ConvertibleBond(Bond):
    def __init__(self, face, ytm, coupon_rate, maturity, conversion_ratio, conversion_price):
        super().__init__(face, ytm, coupon_rate, maturity)
        self.conversion_ratio = conversion_ratio  # number of shares per bond
        self.conversion_price = conversion_price  # price at which bond can convert

    def getPrice(self, stock_price=None):
        # Convertible bond price ≈ max(straight bond price, conversion value)
        straight_price = super().getPrice()
        if stock_price is not None:
            conversion_value = self.conversion_ratio * stock_price
            return max(straight_price, conversion_value)
        else:
            return straight_price

    def getDuration(self):
        # Duration is usually less due to conversion, but we'll use the parent version
        return super().getDuration()

    def __repr__(self):
        return (f"ConvertibleBond(face={self.face}, ytm={self.ytm}, coupon_rate={self.coupon_rate}, "
                f"maturity={self.maturity}, conversion_ratio={self.conversion_ratio}, "
                f"conversion_price={self.conversion_price})")

    def __str__(self):
        return (f"Convertible Bond: Face={self.face}, Coupon={self.coupon_rate*100}%, "
                f"YTM={self.ytm*100}%, Maturity={self.maturity} years, "
                f"Conversion Ratio={self.conversion_ratio}, Conversion Price={self.conversion_price}")

conv_bond = ConvertibleBond(1000, 0.04, 0.05, 5, conversion_ratio=20, conversion_price=50)
print(conv_bond)
print("Price (no stock):", conv_bond.getPrice())
print("Price (stock $55):", conv_bond.getPrice(stock_price=55))
print("Duration:", conv_bond.getDuration())