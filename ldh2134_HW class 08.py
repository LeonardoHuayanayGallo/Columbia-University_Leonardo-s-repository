import numpy as np

class Bond:
    def __init__(self, face, ytm, coupon_rate, maturity):
        self.face = face  # par value (e.g. 1000)
        self.ytm = ytm    # yield to maturity (as decimal, 5% → 0.05)
        self.coupon_rate = coupon_rate  # annual coupon rate (as decimal)
        self.maturity = maturity  # in years

    def getPrice(self):
        # price = PV of coupons + PV of face value
        price = 0
        for t in range(1, self.maturity + 1):
            price += self.coupon_rate * self.face / (1 + self.ytm) ** t
        price += self.face / (1 + self.ytm) ** self.maturity
        return price

    def getDuration(self):
        # Macaulay Duration = weighted average of the times to coupon payments
        price = self.getPrice()
        weighted_sum = 0
        for t in range(1, self.maturity + 1):
            weighted_sum += t * (self.coupon_rate * self.face) / (1 + self.ytm) ** t
        weighted_sum += self.maturity * self.face / (1 + self.ytm) ** self.maturity
        duration = weighted_sum / price
        return duration

    def __repr__(self):
        return f"Bond(face={self.face}, ytm={self.ytm}, coupon_rate={self.coupon_rate}, maturity={self.maturity})"

    def __str__(self):
        return f"Bond: Face={self.face}, Coupon={self.coupon_rate*100}%, YTM={self.ytm*100}%, Maturity={self.maturity} years"

bond1 = Bond(1000, 0.05, 0.06, 5)
print(bond1)
print("Price:", bond1.getPrice())
print("Duration:", bond1.getDuration())

